const descriptions = {
  extName: 'Extension name in the store and chrome://extensions. Maximum 75 characters.',
  extDescription: 'Store summary. Maximum 132 characters.',
  extActionTitle: 'Toolbar tooltip.',
}

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', 'public', '_locales')
const keys = Object.keys(locales.en)
for (const [locale, messages] of Object.entries(locales)) {
  const missing = keys.filter((key) => !(key in messages))
  if (missing.length) throw new Error(`${locale} missing ${missing.join(', ')}`)
  const name = [...messages.extName].length
  const desc = [...messages.extDescription].length
  if (name > 75) throw new Error(`${locale} name is ${name}`)
  if (desc > 132) throw new Error(`${locale} description is ${desc}`)
  const body = {}
  for (const key of keys) {
    body[key] = {
      message: messages[key],
      description: descriptions[key] ?? 'Sprout interface string.',
    }
  }
  const dir = path.join(root, locale)
  mkdirSync(dir, { recursive: true })
  writeFileSync(path.join(dir, 'messages.json'), `${JSON.stringify(body, null, 2)}\n`)
  console.log(locale, 'name', name, 'description', desc)
}
